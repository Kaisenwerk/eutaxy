/**
 * The files `eutaxy check` writes into `<scenario dir>/.eutaxy/` before
 * running Vitest: a test that performs the check inside workerd and prints
 * the verdict on one marked line, and a Vitest config with the Cloudflare
 * plugin pointed at the scenario's wrangler config. For a scenario with
 * callees the test imports their modules, the config names a generated main
 * module and adds their resources through miniflare options (`callees.ts`).
 */

import { dirname, join } from "node:path";
import { neverCalled } from "./callees.ts";
import { unhandledErrorsFile } from "./vitest-failure.ts";

/** Key under which the generated test stores its result in the Vitest task meta, read back from the JSON reporter. */
export const metaKey = "eutaxy";

export interface GeneratedCheck {
  readonly seed: string;
  readonly maxRuns?: number;
  /** Replaces the scenario's time budget. */
  readonly budgetMs?: number;
  /** Exhaustive exploration instead of seeded. */
  readonly exhaustive?: boolean;
  /** Import specifier of the scenario from the generated test (e.g. "../scenario.sim.ts"). */
  readonly scenarioImport: string;
  /** Import specifier of the Worker's entry when it lies outside the scenario's directory, where the test's glob does not reach. */
  readonly workerImport?: string;
  /** The callees the scenario names: each one's binding, Worker name and the import specifier of its module. */
  readonly callees?: readonly {
    readonly binding: string;
    readonly name: string;
    readonly importPath: string;
    /** From the caller's config: the entrypoint the binding reaches, the props it carries. */
    readonly entrypoint?: string;
    readonly props?: Readonly<Record<string, unknown>>;
    /** The callee is the scenario's own Worker, called back by a Worker it called. */
    readonly self?: boolean;
  }[];
  /** SQL files outside the scenario's directory (a callee's schema), by the key `schemasFor` looks up, with their import specifiers. */
  readonly sqlImports?: readonly { readonly key: string; readonly importPath: string }[];
  /** Qualified binding names that are aliases of the caller's bindings (shared resources). */
  readonly aliases?: Readonly<Record<string, string>>;
}

/**
 * The generated test: the module globs (Vite resolves them at build time,
 * so they must be written in the test) and one call to `checkInWorkerd`,
 * which does the rest.
 */
export function checkTestSource(g: GeneratedCheck): string {
  const options =
    `seed: ${JSON.stringify(g.seed)}` +
    (g.maxRuns === undefined ? "" : `, maxRuns: ${g.maxRuns}`) +
    (g.budgetMs === undefined ? "" : `, budgetMs: ${g.budgetMs}`) +
    (g.exhaustive ? ", exhaustive: true" : "");
  const callees = g.callees ?? [];
  const sqlImports = g.sqlImports ?? [];
  const calleeImports = callees.map(
    (c, i) => `import * as callee_${i} from ${JSON.stringify(c.importPath)};\n`,
  );
  const sqlImportLines = sqlImports.map(
    (f, i) => `import sql_${i} from ${JSON.stringify(`${f.importPath}?raw`)};\n`,
  );
  const workerImportLine =
    g.workerImport === undefined
      ? ""
      : `import * as workerModule from ${JSON.stringify(g.workerImport)};\n`;
  const workerOption = g.workerImport === undefined ? "" : ", worker: workerModule";
  const calleesOption =
    callees.length === 0
      ? ""
      : `, callees: { ${callees
          .map(
            (c, i) =>
              `${JSON.stringify(c.binding)}: { name: ${JSON.stringify(c.name)}, exports: callee_${i}${c.entrypoint === undefined ? "" : `, entrypoint: ${JSON.stringify(c.entrypoint)}`}${c.props === undefined ? "" : `, props: ${JSON.stringify(c.props)}`}${c.self ? ", self: true" : ""} }`,
          )
          .join(", ")} }`;
  const extraSql =
    sqlImports.length === 0
      ? ""
      : `, extraSql: { ${sqlImports.map((f, i) => `${JSON.stringify(f.key)}: sql_${i}`).join(", ")} }`;
  const aliases =
    g.aliases === undefined || Object.keys(g.aliases).length === 0
      ? ""
      : `, aliases: ${JSON.stringify(g.aliases)}`;
  return `// Generated by eutaxy check; deleted after the run.
import { checkInWorkerd } from "eutaxy/cloudflare";
import { env } from "cloudflare:workers";
import * as durableObjects from "cloudflare:test";
import { test } from "vitest";
import scenario from ${JSON.stringify(g.scenarioImport)};
${workerImportLine}${calleeImports.join("")}${sqlImportLines.join("")}import { specEntries } from "./specs.ts";

const sqlFiles = import.meta.glob("../**/*.sql", { query: "?raw", import: "default", eager: true }) as Record<string, string>;
const modules = import.meta.glob(["../**/*.ts", "!../**/*.test.ts", "!../**/*.sim.ts", "!../**/node_modules/**", "!../**/.eutaxy/**"]);

test("eutaxy check", async ({ task }) => {
  task.meta[${JSON.stringify(metaKey)}] = await checkInWorkerd({ scenario, env, durableObjects, sqlFiles, modules, specEntries${workerOption}${calleesOption}${extraSql}${aliases}, ${options} });
});
`;
}

/**
 * The plugin's main module, absolute: the scenario's Worker entry, or for a scenario with callees the
 * generated module re-exporting the caller's and the callees' classes, with the callees' resources.
 */
export interface CalleeIsolate {
  readonly main: string;
  /** The miniflare options as source (an object literal); only a scenario with callees has them. */
  readonly miniflare?: string;
}

export function vitestConfigSource(
  wranglerConfigPath: string,
  testPath: string,
  outputFile: string,
  isolate?: CalleeIsolate,
): string {
  const plugin =
    isolate === undefined
      ? `cloudflareTest({ wrangler: { configPath: ${JSON.stringify(wranglerConfigPath)} } })`
      : `cloudflareTest({ main: ${JSON.stringify(isolate.main)}, wrangler: { configPath: ${JSON.stringify(wranglerConfigPath)} }${isolate.miniflare === undefined ? "" : `, miniflare: ${isolate.miniflare}`} })`;
  // A service binding the scenario scripts or runs as a callee is never called; the value must exist.
  const helpers =
    isolate?.miniflare === undefined
      ? ""
      : `const ${neverCalled} = () => new Response("eutaxy: a service binding the scenario scripts or runs as a callee is never called", { status: 500 });\n\n`;
  return `// Generated by eutaxy check; deleted after the run.
import { writeFileSync } from "node:fs";
import { cloudflareTest } from "@cloudflare/vitest-plugin";
import { defineConfig } from "vitest/config";

${helpers}export default defineConfig({
  // Vite's cache, kept with the generated files so it goes when they do (its default is the
  // project's node_modules/.vite, which a check would leave behind in the scenario's directory).
  cacheDir: ${JSON.stringify(join(dirname(testPath), ".vite"))},
  plugins: [${plugin}],
  test: {
    include: [${JSON.stringify(testPath)}],
    testTimeout: 600_000,
    // An error nothing handled fails the run but is not in the JSON report; kept for the command to tell.
    reporters: ["json", { onTestRunEnd(_modules, errors) {
      if (errors.length > 0)
        writeFileSync(${JSON.stringify(unhandledErrorsFile(outputFile))}, JSON.stringify(errors.map((e) => ({ type: e.type, message: e.message, stack: e.stack }))));
    } }],
    outputFile: ${JSON.stringify(outputFile)},
  },
});
`;
}
