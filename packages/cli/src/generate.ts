/**
 * The files `eutaxy check` writes into `<scenario dir>/.eutaxy/` before
 * running Vitest: a test that performs the check inside workerd and prints
 * the verdict on one marked line, and a Vitest config with the Cloudflare
 * plugin pointed at the scenario's wrangler config.
 */

/** Key under which the generated test stores its result in the Vitest task meta, read back from the JSON reporter. */
export const metaKey = "eutaxy";

export interface GeneratedCheck {
  readonly seed: string;
  readonly maxRuns?: number;
  /** Exhaustive exploration instead of seeded. */
  readonly exhaustive?: boolean;
  /** Import specifier of the scenario from the generated test (e.g. "../scenario.sim.ts"). */
  readonly scenarioImport: string;
}

/** What the generated test stores in its task meta. */
export interface CheckTransport {
  readonly report: unknown;
  /** Set instead of a report when a module the scenario's `specs` names has no usable annotations. */
  readonly specErrors?: readonly {
    readonly module: string;
    readonly line: number;
    readonly message: string;
  }[];
  readonly worker: { readonly entry: string; readonly config: string };
  readonly setup: readonly { readonly kind: string; readonly [key: string]: unknown }[];
  /** The core modules observed (as the scenario's specs name them) and the functions on each. */
  readonly observed?: readonly { readonly module: string; readonly functions: readonly string[] }[];
}

export function checkTestSource(g: GeneratedCheck): string {
  const maxRuns =
    (g.maxRuns === undefined ? "" : `, maxRuns: ${g.maxRuns}`) +
    (g.exhaustive ? ", exhaustive: true" : "");
  return `// Generated by eutaxy check; deleted after the run.
import { checkSpecModule, observeCore, renderJson } from "eutaxy";
import { check, createCloudflarePlatform, type QueueHandler } from "eutaxy/cloudflare";
import { env } from "cloudflare:workers";
import * as cloudflareTest from "cloudflare:test";
import { test } from "vitest";
import scenario from ${JSON.stringify(g.scenarioImport)};
import { specLoaders } from "./specs.ts";

const sqlFiles = import.meta.glob("../**/*.sql", { query: "?raw", import: "default", eager: true }) as Record<string, string>;
const modules = import.meta.glob(["../**/*.ts", "!../**/*.test.ts", "!../**/*.sim.ts", "!../**/node_modules/**", "!../**/.eutaxy/**"]) as Record<string, () => Promise<{ default: QueueHandler }>>;

function key(path: string): string {
  return \`../\${path.replace(/^\\.\\//, "")}\`;
}

test("eutaxy check", async ({ task }) => {
  const schemas: Record<string, string> = {};
  for (const step of scenario.setup) {
    if (step.kind !== "d1") continue;
    const sql = sqlFiles[key(String(step.schemaFile))];
    if (sql === undefined) throw new Error(\`schema file \${String(step.schemaFile)} not found next to the scenario\`);
    schemas[String(step.binding)] = sql;
  }
  const load = modules[key(scenario.worker.entry)];
  if (!load) throw new Error(\`worker entry \${scenario.worker.entry} not found next to the scenario\`);
  const handler = (await load()).default;
  const platform = createCloudflarePlatform({ env, handler, schemas, durableObjects: cloudflareTest });
  // The modules the scenario's specs name: their annotated functions, and the core functions
  // refines invariants name, are observed while it runs.
  const decisions = scenario.invariants.flatMap((i) => (i.kind === "refines" ? [i.decision] : []));
  const specErrors: { module: string; line: number; message: string }[] = [];
  const selected = [];
  for (const path of scenario.specs ?? []) {
    const specKey = \`./\${path.replace(/^(\\.\\/)+/, "")}\`;
    const loadSpec = modules[key(path)];
    if (!loadSpec) {
      specErrors.push({ module: path, line: 0, message: "no such module next to the scenario" });
      continue;
    }
    const namespace = await loadSpec();
    const entry = specLoaders[specKey] ? await specLoaders[specKey]() : undefined;
    const specs = entry?.specs ?? { functions: [], exports: [], errors: [] };
    for (const e of specs.errors) specErrors.push({ module: path, ...e });
    const names = [...new Set([...specs.functions.map((f) => f.name), ...decisions.filter((d) => typeof (namespace as Record<string, unknown>)[d] === "function")])];
    selected.push({ path, key: specKey, namespace, specs, predicates: entry ? entry.predicates(namespace) : {}, names });
  }
  // Decisions are logged by function name: one name in two modules would make them ambiguous.
  const observedIn = new Map<string, string>();
  for (const m of selected)
    for (const n of m.names) {
      const other = observedIn.get(n);
      if (other !== undefined) specErrors.push({ module: m.path, line: 0, message: \`\${n} is observed in both \${other} and \${m.path}; decisions of one name must come from one module\` });
      else observedIn.set(n, m.path);
    }
  if (specErrors.length > 0) {
    task.meta[${JSON.stringify(metaKey)}] = { report: null, specErrors, worker: scenario.worker, setup: scenario.setup };
    return;
  }
  const observers = selected.map((m) => observeCore(m.namespace, m.names));
  let verdict;
  try {
    verdict = await check(scenario, platform, { seed: ${JSON.stringify(g.seed)}${maxRuns} });
  } finally {
    for (const o of observers) o.restore();
  }
  const specs = selected.flatMap((m, i) => checkSpecModule(m.key, m.specs, m.predicates, observers[i]));
  const observed = selected.map((m) => ({ module: m.path, functions: m.names }));
  task.meta[${JSON.stringify(metaKey)}] = { report: JSON.parse(renderJson(verdict, specs)), worker: scenario.worker, setup: scenario.setup, observed };
});
`;
}

export function vitestConfigSource(
  wranglerConfigPath: string,
  testPath: string,
  outputFile: string,
): string {
  return `// Generated by eutaxy check; deleted after the run.
import { cloudflareTest } from "@cloudflare/vitest-plugin";
import { defineConfig } from "vitest/config";

export default defineConfig({
  plugins: [cloudflareTest({ wrangler: { configPath: ${JSON.stringify(wranglerConfigPath)} } })],
  test: {
    include: [${JSON.stringify(testPath)}],
    testTimeout: 600_000,
    reporters: ["json"],
    outputFile: ${JSON.stringify(outputFile)},
  },
});
`;
}
