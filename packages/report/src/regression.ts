/**
 * The Vitest regression emitter. Given a violation, produce a test file that
 * replays its shrunk schedule on the restricted scenario. By default the
 * test expects the invariants to hold, so it fails while the bug exists and
 * passes once it is fixed. With `expect: "violates"` it asserts the recorded
 * violation instead, which is how Eutaxy's own corpus exercises the emitter.
 *
 * The emitter knows nothing about any platform: the caller supplies the
 * import lines and the expression that builds the platform.
 */

import { canonicalJson, type JsonValue, type Violated } from "@eutaxy/core";

export interface RegressionTestOptions {
  /** Import lines for the scenario, the platform's dependencies, and anything the platform expression needs. */
  readonly imports: readonly string[];
  /** An expression evaluating to the `Platform` (may reference the imports). */
  readonly platform: string;
  /** An expression evaluating to the `ScenarioSpec`. */
  readonly scenario: string;
  /** Module that exports `replay`, `restrictSpec` and `checkInvariants`; the public facade by default. */
  readonly engineModule?: string;
  readonly expect?: "holds" | "violates";
}

export function emitRegressionTest(verdict: Violated, options: RegressionTestOptions): string {
  const engineModule = options.engineModule ?? "eutaxy";
  const mode = options.expect ?? "holds";
  const schedule = canonicalJson(verdict.schedule as unknown as JsonValue);
  const kept = canonicalJson([...verdict.keptEvents]);
  const keys = canonicalJson([...verdict.violation.keys]);
  const title =
    mode === "holds"
      ? `${verdict.scenario}: ${verdict.violation.invariant} holds on the recorded schedule`
      : `${verdict.scenario}: ${verdict.violation.invariant} is still violated on the recorded schedule`;
  const assertion =
    mode === "holds"
      ? `  expect(violations.map((v) => \`\${v.invariant}: \${v.message}\`)).toEqual([]);`
      : `  expect(violations.map((v) => [v.invariant, v.keys])).toContainEqual([${JSON.stringify(verdict.violation.invariant)}, ${keys}]);`;
  const lines = [
    "// Generated by Eutaxy. Replays a recorded violation; regenerate rather than edit.",
    `// Scenario ${verdict.scenario}, seed ${String(verdict.seed)}: ${verdict.violation.message}`,
    `import { checkInvariants, replay, restrictSpec } from ${JSON.stringify(engineModule)};`,
    ...options.imports,
    'import { expect, test } from "vitest";',
    "",
    `const schedule = ${schedule} as const;`,
    `const keptEvents = ${kept} as const;`,
    "",
    `test(${JSON.stringify(title)}, async () => {`,
    `  const platform = ${options.platform};`,
    `  const spec = restrictSpec(platform, ${options.scenario}, keptEvents);`,
    "  const log = await replay(spec, platform, schedule);",
    "  const violations = checkInvariants(log, spec.invariants);",
    assertion,
    "});",
    "",
  ];
  return lines.join("\n");
}
