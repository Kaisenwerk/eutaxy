/**
 * The Vitest regression emitter. Given a violation, produce a test file that
 * replays its shrunk schedule on the restricted scenario. By default the
 * test expects the invariants to hold, so it fails while the bug exists and
 * passes once it is fixed. With `expect: "violates"` it asserts the recorded
 * violation instead, which is how Eutaxy's own corpus exercises the emitter.
 *
 * The emitter knows nothing about any platform: the caller supplies the
 * import lines and the expression that builds the platform.
 */

import { canonicalJson, type JsonValue, type Unsupported, type Violated } from "@eutaxy/core";

/** What the emitted test imports, the expressions for its platform and scenario, and what it expects. */
export interface RegressionTestOptions {
  /** Import lines for the scenario, the platform's dependencies, and anything the platform expression needs. */
  readonly imports: readonly string[];
  /** An expression evaluating to the `Platform` (may reference the imports). */
  readonly platform: string;
  /** An expression evaluating to the `ScenarioSpec`. */
  readonly scenario: string;
  /** Module that exports `replay`, `restrictSpec` and `checkInvariants`; the public facade by default. */
  readonly engineModule?: string;
  readonly expect?: "holds" | "violates";
  /**
   * Core functions to observe during the replay, as `refines` needs their
   * decisions in the log: an expression for each module's namespace (from
   * the imports) and the functions to observe on it.
   */
  readonly observe?: readonly {
    readonly namespace: string;
    readonly functions: readonly string[];
  }[];
}

/**
 * A Vitest test file that replays a violation's shrunk schedule: by default it fails while the bug is
 * there and passes once it is fixed.
 */
export function emitRegressionTest(verdict: Violated, options: RegressionTestOptions): string {
  const engineModule = options.engineModule ?? "eutaxy";
  const mode = options.expect ?? "holds";
  const schedule = canonicalJson(verdict.schedule as unknown as JsonValue);
  const kept = canonicalJson([...verdict.keptEvents]);
  const keys = canonicalJson([...verdict.violation.keys]);
  const title =
    mode === "holds"
      ? `${verdict.scenario}: ${verdict.violation.invariant} holds on the recorded schedule`
      : `${verdict.scenario}: ${verdict.violation.invariant} is still violated on the recorded schedule`;
  const assertion =
    mode === "holds"
      ? `  expect(violations.map((v) => \`\${v.invariant}: \${v.message}\`)).toEqual([]);`
      : `  expect(violations.map((v) => [v.invariant, v.keys])).toContainEqual([${JSON.stringify(verdict.violation.invariant)}, ${keys}]);`;
  const observe = options.observe ?? [];
  const replayLines =
    observe.length === 0
      ? ["  const log = await replay(spec, platform, schedule);"]
      : [
          `  const observers = [${observe.map((o) => `observeCore(${o.namespace}, ${JSON.stringify(o.functions)})`).join(", ")}];`,
          "  const log = await replay(spec, platform, schedule).finally(() => {",
          "    for (const o of observers) o.restore();",
          "  });",
        ];
  const lines = [
    "// Generated by Eutaxy. Replays a recorded violation; regenerate rather than edit.",
    `// Scenario ${verdict.scenario}, seed ${String(verdict.seed)}: ${verdict.violation.message}`,
    ...(verdict.pinned === undefined
      ? []
      : [
          `// The run of the scenario's pinned schedule ${JSON.stringify(verdict.pinned)} under seed ${verdict.schedule.seed}, as it ran.`,
        ]),
    `import { checkInvariants, ${observe.length > 0 ? "observeCore, " : ""}replay, restrictSpec } from ${JSON.stringify(engineModule)};`,
    ...options.imports,
    'import { expect, test } from "vitest";',
    "",
    `const schedule = ${schedule} as const;`,
    `const keptEvents = ${kept} as const;`,
    "",
    `test(${JSON.stringify(title)}, async () => {`,
    `  const platform = ${options.platform};`,
    `  const spec = restrictSpec(platform, ${options.scenario}, keptEvents);`,
    ...replayLines,
    "  const violations = checkInvariants(log, spec.invariants);",
    assertion,
    "});",
    "",
  ];
  return lines.join("\n");
}

/**
 * A Vitest test file that replays the run that made a check `UNSUPPORTED`, as its verdict's `replay`
 * names it (each fault at the call it hit, by target, op, arguments and call number), and expects
 * the run to place every fault and reach the same reason: a reproduction to look into, which fails
 * once the run no longer gets there. Only for `unsupported_api`, which one run reaches again (other
 * causes throw). `engineModule` as for `emitRegressionTest`; it exports `runPinned`.
 */
export function emitUnsupportedTest(
  verdict: Unsupported,
  options: Omit<RegressionTestOptions, "expect">,
): string {
  // A leak shows only after other runs, a run that did not replay has nothing to pin, and a pin
  // not placed is the scenario's own: only a run that met something outside the model reaches it again.
  if (verdict.cause !== "unsupported_api")
    throw new Error(
      `a ${verdict.cause} verdict is not reached again by replaying one run; only unsupported_api is`,
    );
  if (verdict.replay === undefined)
    throw new Error("the verdict has no run to replay: it was reached before any run");
  const engineModule = options.engineModule ?? "eutaxy";
  const pinned = canonicalJson(verdict.replay as unknown as JsonValue);
  const observe = options.observe ?? [];
  const runLines =
    observe.length === 0
      ? [`  const run = await runPinned(${options.scenario}, platform, pinned);`]
      : [
          `  const observers = [${observe.map((o) => `observeCore(${o.namespace}, ${JSON.stringify(o.functions)})`).join(", ")}];`,
          `  const run = await runPinned(${options.scenario}, platform, pinned).finally(() => {`,
          "    for (const o of observers) o.restore();",
          "  });",
        ];
  const lines = [
    "// Generated by Eutaxy. Replays the run that made a check UNSUPPORTED; regenerate rather than edit.",
    `// Scenario ${verdict.scenario}, seed ${String(verdict.seed)}: ${verdict.cause}: ${verdict.reason.replace(/\s+/g, " ")}`,
    `import { ${observe.length > 0 ? "observeCore, " : ""}runPinned } from ${JSON.stringify(engineModule)};`,
    ...options.imports,
    'import { expect, test } from "vitest";',
    "",
    // In an object literal a "__proto__" key sets the prototype, so arguments that have one are
    // read back with JSON.parse, which keeps it as an own key the address must match.
    pinned.includes('"__proto__"')
      ? `const pinned = JSON.parse(${JSON.stringify(pinned)});`
      : `const pinned = ${pinned} as const;`,
    "",
    `test(${JSON.stringify(`${verdict.scenario}: the recorded run still reaches what made the check UNSUPPORTED`)}, async () => {`,
    `  const platform = ${options.platform};`,
    ...runLines,
    "  expect(run.unplaced).toEqual([]);",
    `  expect(run.unsupportedReasons.join("; ")).toBe(${JSON.stringify(verdict.reason)});`,
    "});",
    "",
  ];
  return lines.join("\n");
}
